/* AI Execute Runner — ранняя установка темы.
 *
 * Подключается первым скриптом на странице настроек и в попапе, чтобы тема
 * применилась ДО первой отрисовки и не было «вспышки» светлым при тёмной теме.
 *
 * Важно: это отдельный файл, а не инлайн <script>. Политика безопасности
 * расширений (MV3 CSP) запрещает инлайн-скрипты — web-ext lint помечает их
 * предупреждением INLINE_SCRIPT, и в Firefox такой код просто не выполнится.
 */
(function () {
  try {
    var t = localStorage.getItem('axOptionsTheme');
    if (t === 'light' || t === 'dark') {
      document.documentElement.setAttribute('data-ax-theme', t);
    }
  } catch (e) { /* приватный режим — остаёмся на авто-теме */ }
})();
